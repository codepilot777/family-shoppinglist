function detectLang() {
  const nav = (navigator.languages || [navigator.language || '']).map((l) => l.toLowerCase());
  for (const l of nav) {
    if (l.startsWith('zh')) return 'zh';
    if (l.startsWith('id') || l.startsWith('in') || l.startsWith('ms')) return 'id';
    if (l.startsWith('en')) return 'en';
  }
  return 'zh';
}

let current = 'zh';

export function initLang(saved) {
  current = STRINGS[saved] ? saved : detectLang();
  applyDocumentLang();
  return current;
}

export function setLang(lang) {
  if (STRINGS[lang]) current = lang;
  applyDocumentLang();
}

export const getLang = () => current;
export const langInfo = (id = current) => LANGS.find((l) => l.id === id) || LANGS[0];

function applyDocumentLang() {
  document.documentElement.lang = langInfo().htmlLang;
}

export function t(key, vars) {
  let s = STRINGS[current][key] ?? STRINGS.zh[key] ?? key;
  if (vars) for (const [k, v] of Object.entries(vars)) s = s.replaceAll(`{${k}}`, v);
  return s;
}
